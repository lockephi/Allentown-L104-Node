@dataclass
class ClassicalSnapshot:
    """
    A single classical shadow snapshot.

    Generated by applying random Clifford U, measuring in computational basis,
    then inverting: |snap⟩ = U†|b⟩ where b is measurement outcome.

    The classical shadow is the collection of these snapshots.
    """
    snapshot_id: str
    unitary_seed: int           # Seed for reproducible Clifford generation
    measurement_outcome: str      # Bitstring measurement result
    clifford_depth: int           # Depth of random Clifford circuit
    timestamp: float = field(default_factory=time.time)

    def compute_snapshot_state(self, num_qubits: int) -> np.ndarray:
        """
        Reconstruct the snapshot state |snap⟩ = U†|b⟩.

        For classical shadow tomography, we store the unitary and outcome,
        and reconstruct the snapshot state when needed for prediction.
        """
        # Generate the Clifford unitary from seed
        U = self._generate_clifford_unitary(num_qubits, self.unitary_seed)

        # Create measurement basis state |b⟩
        b_state = np.zeros(2 ** num_qubits, dtype=complex)
        idx = int(self.measurement_outcome, 2)
        b_state[idx] = 1.0

        # Apply U†: |snap⟩ = U†|b⟩
        U_dag = U.conj().T
        snapshot = U_dag @ b_state

        return snapshot

    def _generate_clifford_unitary(self, n: int, seed: int) -> np.ndarray:
        """Generate n-qubit Clifford unitary from seed."""
        rng = np.random.RandomState(seed)

        # Simplified Clifford: random tensor product of single-qubit Cliffords
        # plus random CNOT connections
        I = np.eye(2, dtype=complex)
        H_gate = np.array([[1, 1], [1, -1]], dtype=complex) / np.sqrt(2)
        S_gate = np.array([[1, 0], [0, 1j]], dtype=complex)

        single_cliffords = [I, H_gate, S_gate, H_gate @ S_gate]

        # Start with random single-qubit Cliffords
        U = np.eye(1, dtype=complex)
        for _ in range(n):
            gate = single_cliffords[rng.randint(0, 4)]
            U = np.kron(U, gate)

        # Add random CNOT layers
        for _ in range(self.clifford_depth // 2):
            # Random CNOT between random qubit pairs
            q1 = rng.randint(0, n)
            q2 = rng.randint(0, n)
            if q1 != q2:
                CNOT_full = self._build_cnot(n, q1, q2)
                U = CNOT_full @ U

        return U

    def _build_cnot(self, n: int, control: int, target: int) -> np.ndarray:
        """Build n-qubit CNOT matrix with given control and target."""
        # Build as tensor product structure
        dim = 2 ** n
        CNOT = np.eye(dim, dtype=complex)

        # Flip target when control is |1⟩
        for i in range(dim):
            bits = [(i >> j) & 1 for j in range(n)]
            if bits[control] == 1:
                # Flip target
                new_i = i ^ (1 << target)
                CNOT[i, i] = 0
                CNOT[new_i, i] = 1

        return CNOT


